export interface TransactionReceiptData {
  reference: string;
  amount: number;
  recipient: string;
  completedAt: string;
  method: string;
  status: "SUCCESS" | "FAILED" | "HELD";
  message?: string;
}

interface TransactionReceiptProps {
  transaction: TransactionReceiptData;
}

const formatINR = (amount: number) =>
  new Intl.NumberFormat("en-IN", {
    style: "currency",
    currency: "INR",
    maximumFractionDigits: 2,
  }).format(amount);

export const TransactionReceipt = ({
  transaction,
}: TransactionReceiptProps) => {
  const rows = [
    ["Transaction reference", transaction.reference],
    ["Recipient", transaction.recipient],
    ["Payment method", transaction.method],
    ["Date and time", transaction.completedAt],
    ["Status", transaction.status],
  ];

  return (
    <section className="rounded-2xl border border-slate-200 bg-white p-5">
      <div className="border-b border-dashed border-slate-300 pb-5 text-center">
        <p className="text-sm text-slate-500">Transaction amount</p>
        <p className="mt-1 text-3xl font-bold text-slate-900">
          {formatINR(transaction.amount)}
        </p>
        <p className="mt-2 text-sm font-semibold text-slate-700">
          NeoBank demo receipt
        </p>
      </div>

      <dl className="mt-4 space-y-3">
        {rows.map(([label, value]) => (
          <div key={label} className="flex flex-col gap-1 sm:flex-row sm:justify-between">
            <dt className="text-sm text-slate-500">{label}</dt>
            <dd className="break-all text-sm font-semibold text-slate-800 sm:max-w-[60%] sm:text-right">
              {value}
            </dd>
          </div>
        ))}
      </dl>

      {transaction.message && (
        <p className="mt-4 rounded-lg bg-slate-50 p-3 text-sm text-slate-600">
          {transaction.message}
        </p>
      )}

      <p className="mt-4 text-center text-xs text-slate-400">
        This receipt is generated by a frontend simulation.
      </p>
    </section>
  );
};

export default TransactionReceipt;